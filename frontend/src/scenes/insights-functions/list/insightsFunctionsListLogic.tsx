export const shouldShowInsightsFunction = (insightsFunction: InsightsFunctionType, user?: UserType | null): boolean => {
    if (!user) {
        return false
    }
    if (insightsFunction.name.includes(CDP_TEST_HIDDEN_FLAG) && !user.is_impersonated && !user.is_staff) {
        return false
    }
    return true
}

