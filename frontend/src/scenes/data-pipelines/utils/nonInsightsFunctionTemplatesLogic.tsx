export const nonInsightsFunctionTemplatesLogic = kea<nonInsightsFunctionTemplatesLogicType>([
    props({} as NonInsightsFunctionTemplatesLogicProps),
    path((key) => ['scenes', 'data-pipelines', 'utils', 'nonInsightsFunctionTemplatesLogic', key]),

    connect(({ availableSources }: NonInsightsFunctionTemplatesLogicProps) => ({
        values: [
            sourceWizardLogic({ availableSources }),
            ['connectors', 'manualConnectors'],
            featureFlagLogic,
            ['featureFlags'],
            userLogic,
            ['user'],
        ],
    })),

    selectors({
        insightsFunctionTemplatesDataWarehouseSources: [
            (s) => [s.connectors, s.manualConnectors, s.featureFlags],
            (
                connectors: SourceConfig[],
                manualConnectors: {
                    name: string
                    type: import('~/types').ManualLinkSourceType
                }[],
                featureFlags: import('lib/logic/featureFlagLogic').FeatureFlagsSet
            ): InsightsFunctionTemplateType[] => {
                const managed = connectors.map((connector: SourceConfig): InsightsFunctionTemplateType => {
                    const featureFlagDefined = !!connector.featureFlag
                    const featureFlagRaw = featureFlags[connector.featureFlag as FeatureFlagKey]
                    // Treat "flag declared but absent in featureFlags" as off — non-cloud
                    // featureFlagLogic only exposes truthy flags, so an undefined lookup means the
                    // gate is closed for this user. Without this coercion, getSourceDisplayStatus
                    // falls back to `unreleasedSource` and any flagged-but-not-unreleased source
                    // (e.g. plain) would render as connectable instead of "Notify me".
                    const featureFlagValue: boolean | undefined = featureFlagDefined ? !!featureFlagRaw : undefined
                    const unreleasedValue = !!connector.unreleasedSource
                    const { status, descriptionEl } = getSourceDisplayStatus(unreleasedValue, featureFlagValue)
                    // Only surface alpha/beta while the source is actually connectable — a source
                    // that renders as "coming_soon" (Roadmap tag) shouldn't also advertise "Beta".
                    const releaseStatus =
                        status === 'stable' && connector.releaseStatus && connector.releaseStatus !== 'ga'
                            ? connector.releaseStatus
                            : undefined

                    return {
                        id: `managed-${connector.name}`,
                        type: 'source',
                        name: connector.label ?? connector.name,
                        icon_url: connector.iconPath,
                        icon_class_name: connector.iconClassName,
                        status: status,
                        description: descriptionEl,
                        code: '',
                        code_language: 'script',
                        inputs_schema: [],
                        filters: null,
                        masking: null,
                        free: true,
                        featured: connector.featured ?? false,
                        releaseStatus,
                    }
                })
                const selfManaged = manualConnectors.map(
                    (source): InsightsFunctionTemplateType => ({
                        id: `self-managed-${source.type}`,
                        type: 'source',
                        name: source.name,
                        icon_url: DATA_WAREHOUSE_SOURCE_ICON_MAP[source.type],
                        status: 'stable',
                        description: (
                            <>
                                Data will be queried directly from your data source that you manage.{' '}
                                <Link to="https://hanzo.ai/docs/cdp/sources">Learn more</Link>
                            </>
                        ),
                        code: '',
                        code_language: 'script',
                        inputs_schema: [],
                        filters: null,
                        masking: null,
                        free: true,
                    })
                )

                return [...managed, ...selfManaged]
            },
        ],

        insightsFunctionTemplatesBatchExports: [
            (s) => [s.featureFlags, s.user],
            (
                featureFlags: import('lib/logic/featureFlagLogic').FeatureFlagsSet,
                user: null | import('~/types').UserType
            ): InsightsFunctionTemplateType[] => {
                // HTTP is currently only used for Cloud to Cloud migrations and shouldn't be accessible to users
                const httpEnabled =
                    featureFlags[FEATURE_FLAGS.BATCH_EXPORTS_POSTFN_HTTP] || user?.is_impersonated || user?.is_staff

                const services = BATCH_EXPORT_SERVICE_NAMES.filter((service) => {
                    // Legacy alias — superseded in the picker by AwsS3 + S3Compatible. Kept in the
                    // service list so existing 'S3' rows still load and render.
                    if (service === 'S3') {
                        return false
                    }
                    // HTTP is only for Cloud-to-Cloud migrations; gated behind a flag / staff.
                    if (service === 'HTTP') {
                        return httpEnabled
                    }
                    return true
                })

                return services.map(
                    (service): InsightsFunctionTemplateType => ({
                        id: `batch-export-${service}`,
                        type: 'destination',
                        name: humanizeBatchExportName(service),
                        icon_url: BATCH_EXPORT_ICON_MAP[service],
                        status: service === 'Databricks' ? 'beta' : service === 'AzureBlob' ? 'beta' : 'stable',
                        code: '',
                        code_language: 'script',
                        inputs_schema: [],
                        filters: null,
                        masking: null,
                        free: false,
                        description: humanizeBatchExportDescription(service),
                    })
                )
            },
        ],
    }),
])
