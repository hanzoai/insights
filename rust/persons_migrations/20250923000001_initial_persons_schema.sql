-- PersonOverride table
CREATE TABLE IF NOT EXISTS insights_personoverride (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    oldest_event TIMESTAMP WITH TIME ZONE NOT NULL,
    version BIGINT,
    team_id BIGINT NOT NULL,
    old_person_id INTEGER NOT NULL REFERENCES insights_personoverridemapping(id),
    override_person_id INTEGER NOT NULL REFERENCES insights_personoverridemapping(id)
);

CREATE INDEX IF NOT EXISTS insights_personoverride_old_person_id_4c1deac0 ON insights_personoverride (old_person_id);
CREATE INDEX IF NOT EXISTS insights_personoverride_override_person_id_9f32aab1 ON insights_personoverride (override_person_id);
CREATE INDEX IF NOT EXISTS insights_personoverride_team_id_92291e67 ON insights_personoverride (team_id);
CREATE UNIQUE INDEX IF NOT EXISTS unique_override_per_old_person_id ON insights_personoverride (team_id, old_person_id);

-- Idempotently add check constraint
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint 
        WHERE conname = 'old_person_id_different_from_override_person_id' 
        AND conrelid = 'insights_personoverride'::regclass
    ) THEN
        ALTER TABLE insights_personoverride ADD CONSTRAINT old_person_id_different_from_override_person_id 
            CHECK (old_person_id != override_person_id);
    END IF;
END $$;

CREATE EXTENSION IF NOT EXISTS btree_gist;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint 
        WHERE conname = 'exclude_override_person_id_from_being_old_person_id' 
        AND conrelid = 'insights_personoverride'::regclass
    ) THEN
        ALTER TABLE insights_personoverride ADD CONSTRAINT exclude_override_person_id_from_being_old_person_id 
            EXCLUDE USING gist (team_id WITH =, override_person_id WITH =, old_person_id WITH <>) 
            DEFERRABLE INITIALLY DEFERRED;
    END IF;
END $$;

