export const mascotModeLogic = kea<mascotModeLogicType>([
    path(['mascot', 'mascotModeLogic']),
    connect({
        values: [userLogic, ['user'], membersLogic, ['members']],
        actions: [membersLogic, ['ensureAllMembersLoaded']],
    }),
    actions({
        setMascotMode: (hedgeHogMode: MascotModeInterface) => ({ hedgeHogMode }),
        setMascotModeEnabled: (enabled: boolean) => ({ enabled }),
        toggleMascotMode: true,
        loadRemoteConfig: true,
        updateRemoteConfig: (config: Partial<MascotConfig>) => ({ config }),
        setRemoteConfigUpdateDisabled: (disabled: boolean) => ({ disabled }),
        syncGame: true,
        syncFromState: true,
    }),

    reducers(() => ({
        mascotMode: [
            null as MascotModeInterface | null,
            {
                setMascotMode: (_, { hedgeHogMode }) => hedgeHogMode,
            },
        ],
        remoteConfigUpdateDisabled: [
            false,
            {
                setRemoteConfigUpdateDisabled: (_, { disabled }) => disabled,
            },
        ],
    })),

    loaders(({ values, actions }) => ({
        remoteConfig: [
            null as Partial<MascotConfig> | null,
            {
                loadRemoteConfig: async () => {
                    const endpoint = '/api/users/@me/mascot_config'
                    const mountedToolbarConfigLogic = toolbarConfigLogic.findMounted()
                    if (mountedToolbarConfigLogic) {
                        // If toolbarConfigLogic is mounted, we're inside the Toolbar.
                        if (!mountedToolbarConfigLogic.values.isAuthenticated) {
                            return null
                        }
                        // The config is cosmetic - on any request failure (network, auth,
                        // non-JSON body) fall back to defaults rather than raising an error.
                        try {
                            const response = await toolbarFetch(endpoint, 'GET')
                            if (!response.ok) {
                                return null
                            }
                            return await response.json()
                        } catch {
                            return null
                        }
                    }
                    return await api.get<Partial<MascotConfig>>(endpoint)
                },

                updateRemoteConfig: async ({ config }) => {
                    const endpoint = '/api/users/@me/mascot_config'
                    const payload = {
                        ...values.mascotConfig,
                        ...config,
                    }

                    const mountedToolbarConfigLogic = toolbarConfigLogic.findMounted()
                    if (mountedToolbarConfigLogic) {
                        // Inside the Toolbar the OAuth token is scoped to `user:read` only
                        // (TOOLBAR_OAUTH_SCOPES grants no `user:write`), so persisting the mascot
                        // config would 403 — and toolbarFetch turns any 403 into a session reset,
                        // kicking the user out of the Toolbar. Keep the config local to this session.
                        return mountedToolbarConfigLogic.values.isAuthenticated ? payload : null
                    }

                    try {
                        const newConfig: Partial<MascotConfig> = await api.update(endpoint, payload)
                        return newConfig ?? null
                    } catch (e) {
                        console.error('Failed to update mascot remote config', e)
                        actions.setRemoteConfigUpdateDisabled(true)
                        return values.remoteConfig
                    }
                },
            },
        ],
    })),

    selectors({
        mascotConfig: [
            (s) => [s.remoteConfig],
            (remoteConfig: Partial<MascotConfig> | null): MascotConfig => {
                return sanitizeMascotConfig({
                    ...remoteConfig,
                })
            },
        ],

        mascotModeEnabled: [
            (s) => [s.mascotConfig],
            (mascotConfig: MascotConfig): boolean => {
                return !!mascotConfig.enabled
            },
        ],

        minimalMascotConfig: [
            (s) => [s.mascotConfig],
            (mascotConfig: MascotConfig): MinimalMascotConfig => {
                const forcedHedeghogProfile: MinimalMascotConfig = {
                    use_as_profile: true,
                    color: mascotConfig?.actor_options?.color,
                    skin: mascotConfig?.actor_options?.skin,
                    accessories: mascotConfig?.actor_options?.accessories,
                }

                return forcedHedeghogProfile
            },
        ],
    }),

    listeners(({ actions, values }) => ({
        setMascotModeEnabled: ({ enabled }) => {
            if (!values.remoteConfigUpdateDisabled) {
                actions.updateRemoteConfig({
                    enabled,
                })
            }

            insights.capture(enabled ? 'mascot mode enabled' : 'mascot mode disabled')
        },
        toggleMascotMode: () => {
            actions.setMascotModeEnabled(!values.mascotModeEnabled)
        },

        updateRemoteConfigSuccess: ({ remoteConfig }) => {
            const theUserLogic = userLogic.findMounted()

            if (theUserLogic) {
                userLogic
                    .findMounted()
                    ?.actions.loadUserSuccess({ ...theUserLogic.values.user, mascot_config: remoteConfig } as any)
            }
        },

        syncGame: () => {
            const { mascotMode, mascotConfig } = values
            if (!mascotMode || !mascotConfig) {
                return
            }

            // Sync the actor options to the game
            mascotMode.stateManager?.setMascot(mascotConfig.actor_options)
        },

        syncFromState: () => {
            const { mascotMode, remoteConfigUpdateDisabled } = values
            if (!mascotMode || remoteConfigUpdateDisabled) {
                return
            }
            const state = mascotMode.stateManager?.getState()
            const player = state?.options

            if (!player) {
                return
            }

            const lastPlayerState = JSON.stringify(values.mascotConfig.actor_options)
            const currentPlayerState = JSON.stringify(player)
            if (lastPlayerState !== currentPlayerState) {
                // On change, update the remote config
                actions.updateRemoteConfig({
                    actor_options: player,
                })
            }
        },
    })),

    subscriptions(({ actions, values }) => ({
        mascotConfig: () => {
            if (values.mascotModeEnabled) {
                actions.ensureAllMembersLoaded()
            }
            actions.syncGame()
        },
        mascotMode: () => actions.syncGame(),
    })),

    afterMount(({ actions, cache }) => {
        const loadedUser = userLogic.findMounted()?.values.user
        if (loadedUser) {
            actions.loadRemoteConfigSuccess(loadedUser.mascot_config ?? {})
        } else {
            actions.loadRemoteConfig()
        }

        cache.syncInterval = setInterval(() => {
            actions.syncFromState()
        }, 1000)
    }),

    beforeUnmount(({ cache }) => {
        if (cache.syncInterval) {
            clearInterval(cache.syncInterval)
            cache.syncInterval = null
        }
    }),
])
