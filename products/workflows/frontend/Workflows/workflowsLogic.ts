import type { InsightsFlow } from './insightsflows/types'

export type WorkflowStatusFilter = 'all' | 'active' | 'draft' | 'archived'

const WORKFLOW_STATUS_FILTERS: WorkflowStatusFilter[] = ['all', 'active', 'draft', 'archived']

export const WORKFLOWS_PER_PAGE = 30

export interface WorkflowsFilters {
    search: string
    createdBy: string | null
    status: WorkflowStatusFilter
    page: number
}

const DEFAULT_FILTERS: WorkflowsFilters = { search: '', createdBy: null, status: 'all', page: 1 }

type WorkflowsResult = CountedPaginatedResponse<InsightsFlow>

interface WorkflowsListParams {
    search?: string
    status?: InsightsFlow['status']
    created_by?: string
    limit: number
    offset: number
}

