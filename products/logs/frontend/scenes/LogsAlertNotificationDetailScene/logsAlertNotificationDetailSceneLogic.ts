export const logsAlertNotificationDetailSceneLogic = kea<logsAlertNotificationDetailSceneLogicType>([
    path((key) => [
        'products',
        'logs',
        'frontend',
        'scenes',
        'LogsAlertNotificationDetailScene',
        'logsAlertNotificationDetailSceneLogic',
        key,
    ]),
    props({} as LogsAlertNotificationDetailSceneLogicProps),
    key((props) => `${props.alertId}:${props.insightsFunctionId}`),

    connect({
        values: [teamLogic, ['currentTeamId'], integrationsLogic, ['slackIntegrations']],
    }),

    actions({
        deleteDestination: (displayLabel: string) => ({ displayLabel }),
        deleteDestinationDone: true,
        setInsightsFunctionEnabled: (insightsFunctionId: string, enabled: boolean) => ({ insightsFunctionId, enabled }),
    }),

    reducers({
        hasLoaded: [
            false,
            {
                loadInsightsFunctionsSuccess: () => true,
            },
        ],
        insightsFunctionsError: [
            null as string | null,
            {
                loadInsightsFunctions: () => null,
                loadInsightsFunctionsSuccess: () => null,
                loadInsightsFunctionsFailure: (_, { error }: { error: string }) => error || 'Failed to load destinations',
            },
        ],
        isDeleting: [
            false,
            {
                deleteDestination: () => true,
                deleteDestinationDone: () => false,
            },
        ],
        togglingInsightsFunctionIds: [
            [] as string[],
            {
                setInsightsFunctionEnabled: (state, { insightsFunctionId }) =>
                    state.includes(insightsFunctionId) ? state : [...state, insightsFunctionId],
                loadInsightsFunctionsSuccess: () => [],
                loadInsightsFunctionsFailure: () => [],
            },
        ],
    }),

    loaders(({ values, props }) => ({
        alert: [
            null as LogsAlertConfigurationApi | null,
            {
                loadAlert: async () => {
                    if (!values.currentTeamId) {
                        return null
                    }
                    return logsAlertsRetrieve(String(values.currentTeamId), props.alertId)
                },
            },
        ],
        insightsFunctions: [
            [] as InsightsFunctionType[],
            {
                loadInsightsFunctions: async () => {
                    if (!values.currentTeamId) {
                        return []
                    }
                    const response = await api.insightsFunctions.list({
                        types: ['internal_destination'],
                        filter_groups: [buildLogsAlertFilterConfig(props.alertId)],
                        full: true,
                    })
                    return response.results
                },
            },
        ],
    })),

    selectors({
        alertId: [() => [(_, props) => props.alertId], (alertId: string): string => alertId],
        insightsFunctionId: [() => [(_, props) => props.insightsFunctionId], (id: string): string => id],
        firstSlackIntegration: [
            (s) => [s.slackIntegrations],
            (slackIntegrations: IntegrationType[] | undefined): IntegrationType | undefined => slackIntegrations?.[0],
        ],
        destinationGroup: [
            (s) => [s.insightsFunctions, s.insightsFunctionId],
            (insightsFunctions: InsightsFunctionType[], insightsFunctionId: string): LogsAlertDestinationGroup | null => {
                const groups = groupLogsAlertDestinations(insightsFunctions, () => null)
                return groups.find((g) => g.insightsFunctions.some((hf) => hf.id === insightsFunctionId)) ?? null
            },
        ],
        breadcrumbs: [
            (s) => [s.alert, s.destinationGroup, s.alertId],
            (
                alert: LogsAlertConfigurationApi | null,
                group: LogsAlertDestinationGroup | null,
                alertId: string
            ): Breadcrumb[] => [
                {
                    key: Scene.Logs,
                    name: 'Logs',
                    path: `${urls.logs()}?activeTab=alerts`,
                    iconType: 'logs',
                },
                {
                    key: Scene.LogsAlertDetail,
                    name: alert?.name ?? 'Alert',
                    path: urls.logsAlertDetail(alertId, 'notifications'),
                    iconType: 'logs',
                },
                {
                    key: Scene.LogsAlertNotificationDetail,
                    name: group?.label ?? 'Destination',
                    iconType: 'logs',
                },
            ],
        ],
    }),

    listeners(({ actions, values, props }) => ({
        deleteDestination: async ({ displayLabel }) => {
            const group = values.destinationGroup
            if (!group || !values.currentTeamId) {
                actions.deleteDestinationDone()
                return
            }
            try {
                await logsAlertsDestinationsDeleteCreate(String(values.currentTeamId), props.alertId, {
                    insights_function_ids: group.insightsFunctions.map((hf) => hf.id),
                })
                toast.success(`Removed ${displayLabel}`)
                router.actions.push(urls.logsAlertDetail(props.alertId, 'notifications'))
            } catch (error: unknown) {
                insights.captureException(error, { tag: 'logs-alert-destination-delete' })
                const detail =
                    (error as { detail?: string; message?: string })?.detail ?? (error as { message?: string })?.message
                toast.error(
                    detail ? `Failed to remove ${displayLabel}: ${detail}` : `Failed to remove ${displayLabel}`
                )
            } finally {
                actions.deleteDestinationDone()
            }
        },
        setInsightsFunctionEnabled: async ({ insightsFunctionId, enabled }) => {
            try {
                await api.insightsFunctions.update(insightsFunctionId, { enabled })
            } catch (error: unknown) {
                insights.captureException(error, { tag: 'logs-alert-script-function-toggle' })
                const detail =
                    (error as { detail?: string; message?: string })?.detail ?? (error as { message?: string })?.message
                toast.error(
                    detail
                        ? `Failed to ${enabled ? 'enable' : 'pause'} notification: ${detail}`
                        : `Failed to ${enabled ? 'enable' : 'pause'} notification`
                )
            }
            // Refresh whether the update succeeded or failed — the success path picks up the new state,
            // the failure path reverts the UI to the server's truth. `togglingInsightsFunctionIds` clears
            // on loadInsightsFunctions{Success,Failure}, so the Switch stays disabled until the
            // refreshed list lands (prevents the double-click race against stale local state).
            actions.loadInsightsFunctions()
        },
    })),

    subscriptions(({ values, actions }) => ({
        currentTeamId: (currentTeamId: number | null) => {
            if (!currentTeamId) {
                return
            }
            if (!values.alert && !values.alertLoading) {
                actions.loadAlert()
            }
            if (!values.hasLoaded && !values.insightsFunctionsLoading) {
                actions.loadInsightsFunctions()
            }
        },
    })),

    afterMount(({ actions, values }) => {
        if (values.currentTeamId) {
            actions.loadAlert()
            actions.loadInsightsFunctions()
        }
    }),
])
