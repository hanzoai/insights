-- Initial schema for persons database
-- Tables: person, persondistinctid, personlessdistinctid, personoverridemapping, 
--         personoverride, pendingpersonoverride, flatpersonoverride,
--         featureflaghashkeyoverride, cohortpeople, groups, grouptypemapping

-- Create sequence for person id
CREATE SEQUENCE IF NOT EXISTS insights_person_id_seq;

-- Person table
CREATE TABLE IF NOT EXISTS insights_person (
    id BIGINT NOT NULL DEFAULT nextval('insights_person_id_seq') PRIMARY KEY,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    properties_last_updated_at JSONB,
    properties_last_operation JSONB,
    properties JSONB NOT NULL DEFAULT '{}'::jsonb,
    is_identified BOOLEAN NOT NULL DEFAULT false,
    uuid UUID NOT NULL,
    version BIGINT,
    is_user_id INTEGER,
    team_id INTEGER NOT NULL
);

CREATE INDEX IF NOT EXISTS insights_per_team_id_bec4e5_idx ON insights_person (team_id, id DESC);
CREATE INDEX IF NOT EXISTS insights_person_team_id_325c1b73 ON insights_person (team_id);
CREATE INDEX IF NOT EXISTS insights_person_uuid_82b4a3ed ON insights_person (uuid);

-- Idempotnently add `check constraint for properties size
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint 
        WHERE conname = 'check_properties_size' 
        AND conrelid = 'insights_person'::regclass
    ) THEN
        ALTER TABLE insights_person ADD CONSTRAINT check_properties_size 
            CHECK (pg_column_size(properties) <= 655360) NOT VALID;
    END IF;
END $$;

